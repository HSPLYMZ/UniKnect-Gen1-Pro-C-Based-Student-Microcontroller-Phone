"""Generate firmware/bsp/vector_table.c from stm32f413xx.h.

The vector table is generated (not hand-written) so that slot indices always
match IRQn_Type. Hand-written tables drift silently and produce hard faults
only when an unexpected interrupt fires.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HDR = os.path.join(ROOT, "firmware", "third_party", "cmsis_device_f4",
                   "Include", "stm32f413xx.h")
OUT = os.path.join(ROOT, "firmware", "bsp", "vector_table.c")

CORE = [
    ("NMI_Handler", "NMI"),
    ("HardFault_Handler", "HardFault"),
    ("MemManage_Handler", "MemManage"),
    ("BusFault_Handler", "BusFault"),
    ("UsageFault_Handler", "UsageFault"),
    (None, None),
    (None, None),
    (None, None),
    (None, None),
    ("SVC_Handler", "SVCall"),
    ("DebugMon_Handler", "DebugMon"),
    (None, None),
    ("PendSV_Handler", "PendSV"),
    ("SysTick_Handler", "SysTick"),
]


def main() -> int:
    text = open(HDR, encoding="utf-8", errors="ignore").read()
    m = re.search(r"typedef enum\s*\{(.*?)\}\s*IRQn_Type;", text, re.S)
    if not m:
        print("IRQn_Type enum not found", file=sys.stderr)
        return 1
    body = m.group(1)
    irqs = []
    for line in body.splitlines():
        mm = re.match(r"\s*([A-Za-z0-9_]+)_IRQn\s*=\s*(-?\d+)", line)
        if mm and int(mm.group(2)) >= 0:
            irqs.append((mm.group(1), int(mm.group(2))))
    irqs.sort(key=lambda x: x[1])
    if not irqs:
        print("no IRQ entries parsed", file=sys.stderr)
        return 1

    n_irq = max(v for _, v in irqs) + 1
    handlers = [f"{n}_IRQHandler" for n, _ in irqs]
    by_index = {v: f"{n}_IRQHandler" for n, v in irqs}

    out = []
    out.append("/* AUTO-GENERATED by tools/gen_vector_table.py -- do not edit. */")
    out.append('#include <stdint.h>')
    out.append("")
    out.append('extern uint32_t _estack;')
    out.append("void Reset_Handler(void);")
    out.append("void Default_Handler(void) __attribute__((noreturn));")
    out.append("")
    out.append("/* Every slot is a weak wrapper around Default_Handler, so a driver that")
    out.append(" * defines e.g. USART6_IRQHandler() overrides it at link time. GCC's")
    out.append(" * alias() cannot be used here: the target must live in the same")
    out.append(" * translation unit, and Default_Handler belongs to board.c. */")
    out.append("#define WEAK_HANDLER(name) \\")
    out.append("    void name(void) __attribute__((weak)); \\")
    out.append("    void name(void) { Default_Handler(); }")
    for name, _ in CORE:
        if name:
            out.append(f"WEAK_HANDLER({name})")
    out.append("")
    out.append("/* Device IRQ handlers: every slot is weak so drivers can override. */")
    for h in handlers:
        out.append(f"WEAK_HANDLER({h})")
    out.append("")
    out.append(f"__attribute__((section(\".isr_vector\"), used))")
    out.append(f"void (*const g_pfnVectors[16 + {n_irq}])(void) = {{")
    out.append("    [0] = (void (*)(void))(&_estack),")
    out.append("    [1] = Reset_Handler,")
    slot = 2
    for name, _ in CORE:
        if name:
            out.append(f"    [{slot}] = {name},")
        slot += 1
    out.append("")
    # Fill reserved slots as well: a NULL entry would send a stray interrupt to
    # 0x00000000, which is the vector table itself and faults unpredictably.
    for i in range(n_irq):
        h = by_index.get(i)
        if h is None:
            out.append(f"    [{16 + i}] = Default_Handler,  /* reserved on F413 */")
        else:
            out.append(f"    [{16 + i}] = {h},")
    out.append("};")
    out.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(f"wrote {OUT}: {n_irq} IRQ slots, {len(handlers)} handlers")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
