"""Generate the GB2312 12x12 font subset from the pinned Fusion Pixel BDF."""
import hashlib
import json
from pathlib import Path
import zipfile

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'.tmp/phone_ui_20261022/font_zh_hans_12.bdf'
DEST=ROOT/'firmware/fonts'


def main():
    DEST.mkdir(exist_ok=True)
    wanted={0xfffd,*range(32,127)}
    for high in range(0xa1,0xf8):
        for low in range(0xa1,0xff):
            try:
                char=bytes([high,low]).decode('gb2312')
                if ord(char)>127:wanted.add(ord(char))
            except UnicodeDecodeError:
                pass
    data=SOURCE.read_bytes()
    manifest=DEST/'FONT_SOURCE.json'
    previous=json.loads(manifest.read_text(encoding='utf-8')) if manifest.exists() else None
    if previous and hashlib.sha256(data).hexdigest()!=previous['bdf_sha256']:
        raise ValueError('Cached BDF differs from pinned source')
    glyphs={}; encoding=None; bbx=None; bitmap=None
    for line in data.decode('ascii').splitlines():
        if line.startswith('STARTCHAR'):encoding=None;bbx=None;bitmap=None
        elif line.startswith('ENCODING '):encoding=int(line.split()[1])
        elif line.startswith('BBX '):bbx=tuple(map(int,line.split()[1:]))
        elif line=='BITMAP':bitmap=[]
        elif line=='ENDCHAR':
            target=0xfffd if encoding==65534 else encoding
            if target in wanted and bitmap is not None and bbx is not None:
                width,height,xoff,yoff=bbx; rows=[0]*12
                for y,value in enumerate(bitmap[:height]):
                    py=10-yoff-height+y
                    for x in range(width):
                        px=xoff+x
                        if 0<=px<12 and 0<=py<12 and value & (1<<(((width+7)//8)*8-1-x)):
                            rows[py]|=1<<(11-px)
                glyphs[target]=rows
            bitmap=None
        elif bitmap is not None and line:bitmap.append(int(line,16))
    missing=wanted-glyphs.keys()
    missing_primary=[cp for cp in missing if 0x4e00<=cp<=0x9fff and chr(cp).encode('gb2312')[0]<=0xd7]
    assert not missing_primary, f'Missing primary Chinese glyphs: {missing_primary[:20]}'
    header='''/* Generated UniKnect Retro 12 Subset. Font data: SIL OFL-1.1.
 * Copyright (c) 2022 TakWolf and upstream authors; see licenses/.
 * Source: Fusion Pixel Font 2026.10.16, zh_Hans 12px monospaced.
 * Generated by tools/generate_phone_font.py; do not edit individual rows. */
#include "phone_font.h"
typedef struct { uint16_t code, rows[12]; } phone_glyph_t;
static const phone_glyph_t s_glyphs[] = {
'''
    records=['{0x%04x,{%s}},'%(cp,','.join('0x%03x'%n for n in glyphs[cp])) for cp in sorted(glyphs)]
    footer='''};
const uint16_t *phone_font_rows(uint32_t code)
{
    unsigned low=0,high=sizeof s_glyphs/sizeof s_glyphs[0];
    while(low<high) {
        unsigned mid=low+(high-low)/2;
        if(s_glyphs[mid].code<code) low=mid+1; else high=mid;
    }
    if(low<sizeof s_glyphs/sizeof s_glyphs[0] && s_glyphs[low].code==code) return s_glyphs[low].rows;
    return s_glyphs[sizeof s_glyphs/sizeof s_glyphs[0]-1].rows;
}
'''
    output=DEST/'phone_font.c';output.write_text(header+'\n'.join(records)+'\n'+footer,encoding='utf-8')
    archive=ROOT/'.tmp/phone_ui_20261022/fusion-pixel-font-12px-monospaced-bdf-v2026.10.16.zip'
    zip_hash='76ed4adde0cc43ae8312041960d586c130c75a9d0f7c1c64a7cace7e4130c358'
    if archive.exists():
        if hashlib.sha256(archive.read_bytes()).hexdigest()!=zip_hash:
            raise ValueError('Font archive differs from GitHub release asset SHA256')
        with zipfile.ZipFile(archive) as z:
            for name in z.namelist():
                if name.endswith('.txt'):
                    target=DEST/'licenses'/name;target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(z.read(name))
    elif not previous or not (DEST/'licenses/OFL.txt').exists():
        raise FileNotFoundError('Restore the pinned font release and licenses before generation')
    record={'upstream':'https://github.com/TakWolf/fusion-pixel-font','release':'2026.10.16',
            'license':'OFL-1.1','generated_name':'UniKnect Retro 12 Subset','glyphs':len(glyphs),
            'unsupported_gb2312_codepoints':[hex(cp) for cp in sorted(missing)],
            'zip_sha256':zip_hash,
            'bdf_sha256':hashlib.sha256(data).hexdigest(),
            'generated_sha256':hashlib.sha256(output.read_bytes()).hexdigest()}
    (DEST/'FONT_SOURCE.json').write_text(json.dumps(record,indent=2),encoding='utf-8')
    print('Generated GB2312 font:',len(glyphs),'glyphs;',output.stat().st_size,'source bytes')


if __name__=='__main__':main()
